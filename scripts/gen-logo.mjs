// Generates src/assets/logo/logo.svg: the "HAVEN PROTOCOL" title mark.
// Letterforms are a 5x7 bitmap face converted to one <path> per colour
// (no <text>, no font dependency). Run with: node scripts/gen-logo.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const out = join(__dirname, '..', 'src', 'assets', 'logo', 'logo.svg');

// 5 wide x 7 tall, '#' = pixel on. Chunky, 45-degree corners where it helps.
const GLYPHS = {
  A: ['.###.', '#...#', '#...#', '#####', '#...#', '#...#', '#...#'],
  V: ['#...#', '#...#', '#...#', '#...#', '#...#', '.#.#.', '..#..'],
  E: ['#####', '#....', '#....', '####.', '#....', '#....', '#####'],
  H: ['#...#', '#...#', '#...#', '#####', '#...#', '#...#', '#...#'],
  T: ['#####', '..#..', '..#..', '..#..', '..#..', '..#..', '..#..'],
  N: ['#...#', '##..#', '##..#', '#.#.#', '#..##', '#..##', '#...#'],
  P: ['####.', '#...#', '#...#', '####.', '#....', '#....', '#....'],
  R: ['####.', '#...#', '#...#', '####.', '#.#..', '#..#.', '#...#'],
  O: ['.###.', '#...#', '#...#', '#...#', '#...#', '#...#', '.###.'],
  C: ['.####', '#....', '#....', '#....', '#....', '#....', '.####'],
  L: ['#....', '#....', '#....', '#....', '#....', '#....', '#####'],
};

const PX = 6; // pixel size
const GAP = 1; // columns between glyphs
const VB_W = 320;
const VB_H = 120;

/** Returns path data for a word drawn starting at (x0, y0). Accent chars get their own path. */
function wordPaths(word, x0, y0, accentChars = '') {
  let main = '';
  let accent = '';
  [...word].forEach((ch, i) => {
    const g = GLYPHS[ch];
    if (!g) throw new Error(`no glyph for ${ch}`);
    const gx = x0 + i * (5 + GAP) * PX;
    g.forEach((row, ry) => {
      // merge horizontal runs into one rect per run
      let rx = 0;
      while (rx < 5) {
        if (row[rx] !== '#') { rx++; continue; }
        let len = 0;
        while (rx + len < 5 && row[rx + len] === '#') len++;
        const d = `M${gx + rx * PX} ${y0 + ry * PX}h${len * PX}v${PX}h${-len * PX}z`;
        if (accentChars.includes(ch)) accent += d; else main += d;
        rx += len;
      }
    });
  });
  return { main, accent };
}

function wordWidth(word) {
  return (word.length * 5 + (word.length - 1) * GAP) * PX;
}

const line1 = 'HAVEN';
const line2 = 'PROTOCOL';
const w1 = wordWidth(line1);
const w2 = wordWidth(line2);
const lineH = 7 * PX;
const lineGap = 10;
const totalH = lineH * 2 + lineGap;
const y1 = Math.round((VB_H - totalH) / 2);
const y2 = y1 + lineH + lineGap;
const x1 = Math.round((VB_W - w1) / 2);
const x2 = Math.round((VB_W - w2) / 2);

const p1 = wordPaths(line1, x1, y1, 'V'); // the V is the amber accent
const p2 = wordPaths(line2, x2, y2);

const shadowDx = 3;
const shadowDy = 3;

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${VB_W} ${VB_H}" shape-rendering="crispEdges">
  <!-- generated by scripts/gen-logo.mjs; edit the script, not this file -->
  <g transform="translate(${shadowDx} ${shadowDy})" fill="#3a2a8c">
    <path d="${p1.main}${p2.main}"/>
    <path d="${p1.accent}" fill="#8a5a1a"/>
  </g>
  <path d="${p1.main}" fill="#7c5cff"/>
  <path d="${p1.accent}" fill="#ffb84d"/>
  <path d="${p2.main}" fill="#a08cff"/>
  <!-- amber corner brackets -->
  <g fill="#ffb84d">
    <path d="M${x2 - 16} ${y1 - 10}h14v4h-10v10h-4zM${x2 + w2 + 2} ${y1 - 10}h14v14h-4v-10h-10z"/>
    <path d="M${x2 - 16} ${y2 + lineH - 4}h4v10h10v4h-14zM${x2 + w2 + 12} ${y2 + lineH - 4}h4v14h-14v-4h10z"/>
  </g>
</svg>
`;
writeFileSync(out, svg);
console.log(`wrote ${out}`);
